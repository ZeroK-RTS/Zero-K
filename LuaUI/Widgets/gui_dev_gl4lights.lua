local function loadExistingLight(name)
	local api = WG["lightsgl4"]
	local udLights = api and api.GetUnitDefLights and api.GetUnitDefLights()
	if not udLights or not state.currentUnitDefID then
		return false
	end
	local lights = udLights[state.currentUnitDefID]
	name = resolveLightKey(lights, name)
	if not lights or type(lights[name]) ~= "table" then
		return false
	end
	local lt = lights[name]
	closePieceDropdown()
	endEditSession()

	state.lightName = tostring(name)
	state.pieceName = lt.pieceName or ""

	for k, v in pairs(defaultLight) do
		state.values[k] = v
	end
	if lt.lightConfig then
		for k, _ in pairs(defaultLight) do
			-- The renderer initializes omitted config fields to zero.
			if k:sub(1, 4) ~= "pdir" and k ~= "ptheta" then
				state.values[k] = lt.lightConfig[k] or 0
			end
		end
		-- For point lights, dir/theta in lightConfig actually mean
		-- world-animation params (mapped to pdir/ptheta in our editor).
		if (lt.lightType or "point") == "point" then
			if lt.lightConfig.dirx ~= nil then
				state.values.pdirx = lt.lightConfig.dirx
			end
			if lt.lightConfig.diry ~= nil then
				state.values.pdiry = lt.lightConfig.diry
			end
			if lt.lightConfig.dirz ~= nil then
				state.values.pdirz = lt.lightConfig.dirz
			end
			if lt.lightConfig.theta ~= nil then
				state.values.ptheta = lt.lightConfig.theta
			end
		end
	elseif lt.lightParamTable then
		local p = lt.lightParamTable
		state.values.posx = p[1]
		state.values.posy = p[2]
		state.values.posz = p[3]
		state.values.radius = p[4]
		state.values.r = p[9]
		state.values.g = p[10]
		state.values.b = p[11]
		state.values.a = p[12]
		state.values.modelfactor = p[13]
		state.values.specular = p[14]
		state.values.scattering = p[15]
		state.values.lensflare = p[16]
		state.values.lifetime = p[18]
		state.values.sustain = p[19]
		state.values.selfshadowing = p[20]
		state.values.color2r = p[21]
		state.values.color2g = p[22]
		state.values.color2b = p[23]
		state.values.colortime = p[24]
		if (lt.lightType or "point") == "cone" then
			state.values.dirx = p[5]
			state.values.diry = p[6]
			state.values.dirz = p[7]
			state.values.theta = p[8]
		elseif lt.lightType == "beam" then
			state.values.pos2x = p[5]
			state.values.pos2y = p[6]
			state.values.pos2z = p[7]
		else
			-- Point light: slots 5-8 hold world-animation params.
			state.values.pdirx = p[5]
			state.values.pdiry = p[6]
			state.values.pdirz = p[7]
			state.values.ptheta = p[8]
		end
	end

	-- Set state BEFORE updating UI: applyAllValuesToUI() triggers onSlider
	-- which calls applyCurrentLight(), and that needs the correct lightType + instance ID
	-- to replace the existing light in-place rather than duplicate it.
	state.editingExisting = name
	state.lightType = lt.lightType or "point"
	applyAllValuesToUI()
	if state.document then
		local pieceDisp = state.document:GetElementById("le-piece-display")
		if pieceDisp then
			pieceDisp.inner_rml = (state.pieceName ~= "" and state.pieceName) or "(unit origin)"
		end
	end
	setLightType(state.lightType)
	updateLightSelector()
	setStatus("Loaded: " .. name)
	return true
end

