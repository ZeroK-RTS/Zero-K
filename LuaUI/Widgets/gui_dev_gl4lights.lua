			editField(field, raw / scale)
		end,

		onNumber = function(ev, field)
			if not state.syncingInputs and ev and ev.current_element then
				editField(field, tonumber(ev.current_element:GetAttribute("value")))
			end
		end,

		onNameChange = function(ev)
			if state.syncingInputs then return end
			local value
			if ev and ev.current_element then
				value = ev.current_element:GetAttribute("value")
			end
			if value == nil and state.dmHandle then value = state.dmHandle.lightName end
			renameCurrentLight(value)
		end,

