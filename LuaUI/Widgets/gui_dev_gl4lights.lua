local function drawPieceMarker(unitID, idx, r, g, b)
	if not unitID or not idx then
		return
	end
	-- GetUnitPiecePosDir supplies world coordinates; GetUnitPiecePosition
	-- supplies a unit-relative position and cannot place a world marker.
	local px, py, pz = spGetUnitPiecePosDir(unitID, idx)
	if not px then
		return
	end
	local rad = EMPTY_PIECE_MARKER_RADIUS

	gl.PushAttrib(GL.ALL_ATTRIB_BITS)
	gl.LineWidth(2)
	gl.Color(r, g, b, 1)
	gl.DepthTest(false)

	gl.BeginEnd(GL.LINES, function()
		gl.Vertex(px - rad, py, pz)
		gl.Vertex(px + rad, py, pz)
		gl.Vertex(px, py - rad, pz)
		gl.Vertex(px, py + rad, pz)
		gl.Vertex(px, py, pz - rad)
		gl.Vertex(px, py, pz + rad)
	end)

	gl.BeginEnd(GL.LINE_LOOP, function()
		gl.Vertex(px + rad, py, pz)
		gl.Vertex(px, py + rad, pz)
		gl.Vertex(px - rad, py, pz)
		gl.Vertex(px, py - rad, pz)
	end)
	gl.BeginEnd(GL.LINE_LOOP, function()
		gl.Vertex(px + rad, py, pz)
		gl.Vertex(px, py, pz + rad)
		gl.Vertex(px - rad, py, pz)
		gl.Vertex(px, py, pz - rad)
	end)
	gl.BeginEnd(GL.LINE_LOOP, function()
		gl.Vertex(px, py + rad, pz)
		gl.Vertex(px, py, pz + rad)
		gl.Vertex(px, py - rad, pz)
		gl.Vertex(px, py, pz - rad)
	end)

	gl.PopAttrib()
end

local function resolveAnchorPiece(light)
	if type(light) ~= "table" or not state.pieceMap then return nil end
	local index = light.pieceName and state.pieceMap[light.pieceName]
	if index then return index end
	index = light.pieceIndex or (light.lightParamTable and light.lightParamTable[25])
	if type(index) == "number" and index > 0 then
		for _, pieceIndex in pairs(state.pieceMap) do
			if pieceIndex == index then return index end
		end
	end
end

local function getAnchorPiece()
	local api = WG["lightsgl4"]
	local definitions = api and api.GetUnitDefLights and api.GetUnitDefLights()
	local lights = definitions and definitions[state.currentUnitDefID]
	if not lights then return nil end
	if not isMultiMode() then return resolveAnchorPiece(lights[state.editingExisting]) end
	local shared
	for name in pairs(state.selectedLights) do
		local index = resolveAnchorPiece(lights[name])
		if not index or (shared and shared ~= index) then return nil end
		shared = index
	end
	return shared
end

local function drawPieceHighlight(index, r, g, b)
	local info = spGetUnitPieceInfo and spGetUnitPieceInfo(state.currentUnitID, index)
	if not info then return end
	if info.isEmpty then
		drawPieceMarker(state.currentUnitID, index, r, g, b)
		return
	end
	if not pieceHighlightShader then return end
	local pieceMatrix = { spGetUnitPieceMatrix(state.currentUnitID, index) }
	local fx, fy, fz, rx, ry, rz, ux, uy, uz = spGetUnitDirection(state.currentUnitID)
	local px, py, pz = spGetUnitPosition(state.currentUnitID)
	if not pieceMatrix[16] or not fx or not px then return end
	-- Match the unit-local basis used for the editor's light positions.
	-- Camera matrices come from the engine, not inherited fixed-function GL
	-- matrices, which can be stale when other GL4 widgets have drawn.
	local modelMatrix = {
		-rx, -ry, -rz, 0, ux, uy, uz, 0, fx, fy, fz, 0, px, py, pz, 1,
	}
	gl.PushAttrib(GL.ALL_ATTRIB_BITS)
	gl.DepthTest(false)
	gl.DepthMask(false)
	gl.AlphaTest(false)
	gl.ColorMask(true)
	gl.Blending(GL.SRC_ALPHA, GL.ONE_MINUS_SRC_ALPHA)
	gl.Culling(GL.BACK)
	gl.PolygonMode(GL.FRONT_AND_BACK, GL.FILL)
	gl.ActiveShader(pieceHighlightShader, function()
		gl.Uniform(pieceHighlightColorLoc, r, g, b, 0.3)
		gl.UniformMatrix(pieceHighlightViewProjLoc, "viewprojection")
		gl.UniformMatrix(pieceHighlightModelLoc, unpack(modelMatrix))
		gl.UniformMatrix(pieceHighlightPieceLoc, unpack(pieceMatrix))
		gl.UnitPiece(state.currentUnitID, index)
	end)
	gl.PopAttrib()
end

-- Transforms a point given in piece-local coords to world coords using the
-- piece's full 4x4 transformation matrix (the same one the deferred rendering
-- shader applies to attached lights). Returns world x, y, z.
--
-- When no piece is selected, falls back to the unit's own world transform via
-- the root piece (index 1 in BAR's 1-based pieceIndex API).
-- The piece-matrix from Spring is local to the unit (piece offset + skeletal
-- animation), NOT a full world matrix. The deferred-rendering shader prepends
-- the unit's world transform: world = unitWorldMatrix * pieceMatrix * lightPos.
-- We replicate that here: first apply piece-local matrix, then rotate+translate
-- by the unit's world transform.
local function pieceLocalToWorld(lx, ly, lz)
	if not state.currentUnitID then
		return nil
	end

	local pieceIdx
	if state.pieceMap and state.pieceName ~= "" and state.pieceMap[state.pieceName] then
		pieceIdx = state.pieceMap[state.pieceName]
	end

	-- Step 1: piece-local transform (turret rotation, attachment offset, etc).
	local m = pieceIdx and { spGetUnitPieceMatrix(state.currentUnitID, pieceIdx) } or nil
	local px, py, pz
	if m and m[1] then
		-- Column-major: m[1..4]=col0, m[5..8]=col1, m[9..12]=col2, m[13..16]=col3 (translation)
		px = m[1] * lx + m[5] * ly + m[9] * lz + m[13]
		py = m[2] * lx + m[6] * ly + m[10] * lz + m[14]
		pz = m[3] * lx + m[7] * ly + m[11] * lz + m[15]
	else
		-- No piece selected: light is in unit-local space directly.
		px, py, pz = lx, ly, lz
	end

	-- Step 2: unit world transform. GetUnitDirection gives front/right/up basis.
	local fx, fy, fz, rx, ry, rz, ux, uy, uz = spGetUnitDirection(state.currentUnitID)
	local upx, upy, upz = spGetUnitPosition(state.currentUnitID)
	if not fx or not upx then
		return nil
	end

	-- Spring/BAR piece-local convention: model +X is the unit's *left* side
	-- (mirrored from intuitive). We negate the X contribution to compensate.
	local wx = -px * rx + py * ux + pz * fx + upx
	local wy = -px * ry + py * uy + pz * fy + upy
	local wz = -px * rz + py * uz + pz * fz + upz
	return wx, wy, wz
end

-- Same as pieceLocalToWorld but for a direction vector (no translation).
local function pieceLocalDirToWorld(lx, ly, lz)
	if not state.currentUnitID then
		return lx, ly, lz
	end

	local pieceIdx
	if state.pieceMap and state.pieceName ~= "" and state.pieceMap[state.pieceName] then
		pieceIdx = state.pieceMap[state.pieceName]
	end

	local m = pieceIdx and { spGetUnitPieceMatrix(state.currentUnitID, pieceIdx) } or nil
	local px, py, pz
	if m and m[1] then
		px = m[1] * lx + m[5] * ly + m[9] * lz
		py = m[2] * lx + m[6] * ly + m[10] * lz
		pz = m[3] * lx + m[7] * ly + m[11] * lz
	else
		px, py, pz = lx, ly, lz
	end

	local fx, fy, fz, rx, ry, rz, ux, uy, uz = spGetUnitDirection(state.currentUnitID)
	if not fx then
		return px, py, pz
	end
	-- Mirror X to match BAR's piece-local convention.
	local wx = -px * rx + py * ux + pz * fx
	local wy = -px * ry + py * uy + pz * fy
	local wz = -px * rz + py * uz + pz * fz
	return wx, wy, wz
end

local function getLightPosWorld()
	local v = state.values
	return pieceLocalToWorld(v.posx or 0, v.posy or 0, v.posz or 0)
end

