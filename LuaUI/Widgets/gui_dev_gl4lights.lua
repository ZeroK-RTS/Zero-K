					listEl:SetAttribute("style", DROPDOWN_LIST_STYLE .. "display: none;")
				end
				state.selectedLights = {}
				refreshMultiModeUI()
				loadExistingLight(arg)
			elseif action == "selectPiece" then
				if state.editingExisting and not isMultiMode() and state.pieceName ~= arg then
					endEditSession()
					pushUndo()
				end
				closePieceDropdown()
				local disp = state.document and state.document:GetElementById("le-piece-display")
				if disp then
					disp.inner_rml = (arg == "") and "(unit origin)" or arg
				end
				state.pieceName = arg
				applyCurrentLight()
			elseif action == "tip" then
				-- Delayed tooltip: queue the candidate; the actual tooltip
				-- appears after 475ms of continuous hover (handled in
				-- widget:Update). mouseout (arg=="") cancels both.
				if arg == "" or arg == nil then
					state.tooltipPending = nil
					state.tooltipPendingSince = nil
					state.tooltip = nil
				else
					if state.tooltipPending ~= arg then
						state.tooltipPending = arg
						state.tooltipPendingSince = Spring.GetTimer()
						state.tooltip = nil -- hide previous tooltip while new one is "warming up"
					end
				end
			elseif action == "copyUnit" then
				local snippet, err = buildUnitSnippet()
				if not snippet then
					setStatus(err or "Could not build unit snippet")
				else
					if spSetClipboard then
						spSetClipboard(snippet)
					end
					spEcho("[LightEditor] Unit snippet copied:\n" .. snippet)
					setStatus("Copied " .. state.currentUnitName .. " block to clipboard")
				end
			elseif action == "undo" then
				restoreHistory(false)
			elseif action == "redo" then
				restoreHistory(true)
			end
		end,

		onSlider = function(ev, field)
			-- Read from the DOM element directly — BAR's RmlUi binding does not
			-- always commit DOM->model before the change/input handler fires.
			if state.syncingInputs or not (ev and ev.current_element) then
				return
			end
