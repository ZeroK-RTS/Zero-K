local function updateTooltipElement()
	if not state.document then
		return
	end
	local el = state.document:GetElementById("le-tooltip")
	if not el then
		return
	end
	local key = state.tooltip
	local text = key and TOOLTIP_TEXTS[key]
	if not text then
		state.tooltipRenderedKey = nil
		if el.SetProperty then
			el:SetProperty("display", "none")
		else
			el:SetAttribute("style", "display: none;")
		end
		return
	end
	if state.tooltipRenderedKey ~= key then
		-- Give wrapped text a block whose full height contributes to the
		-- background, and let layout settle instead of rebuilding each frame.
		el.inner_rml = '<div style="display: block; height: auto; white-space: normal;">' .. text .. '</div>'
		state.tooltipRenderedKey = key
	end
	local mx, my = Spring.GetMouseState()
	local _, vsy = Spring.GetViewGeometry()
	local cssY = (vsy or 0) - my
	local left, top, bottom = mx + 14, (cssY - 32) .. "px", "auto"
	local anchorID = TOOLTIP_ANCHORS[key]
	if anchorID then
		local icon = state.document:GetElementById(anchorID)
		local parent = el.offset_parent or state.document:GetElementById("le-body")
		if icon and parent then
			-- RmlUi layout coordinates already include UI scaling and panel
			-- scrolling. Anchor beside the icon in the tooltip parent's space.
			local gap = 8 * (state.rmlContext.dp_ratio or 1)
			local iconTop = icon.absolute_top - parent.absolute_top
			local height = parent.client_height
			left = icon.absolute_left + icon.offset_width - parent.absolute_left + gap
			if el.offset_width > 0 then
				left = math.max(gap, math.min(left, parent.client_width - el.offset_width - gap))
			end
			if iconTop > height * 0.5 then
				top = "auto"
				bottom = (height - iconTop - icon.offset_height) .. "px"
			else
				top = iconTop .. "px"
			end
		end
	end
	-- SetProperty per-property is more reliable than SetAttribute("style", ...)
	-- in BAR's RmlUi binding; the latter sometimes drops earlier values.
	if el.SetProperty then
		el:SetProperty("display", "block")
		el:SetProperty("height", "auto")
		el:SetProperty("line-height", "18dp")
		el:SetProperty("white-space", "normal")
		el:SetProperty("left", left .. "px")
		el:SetProperty("top", top)
		el:SetProperty("bottom", bottom)
	else
		el:SetAttribute("style", string.format("display: block; height: auto; line-height: 18dp; white-space: normal; left: %.2fpx; top: %s; bottom: %s;", left, top, bottom))
	end
end

