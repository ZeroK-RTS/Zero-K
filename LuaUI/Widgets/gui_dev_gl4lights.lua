local function editField(field, value)
	if not state.editingExisting or isMultiMode() then return end
	local spec = fieldSpecs[field]
	if not spec then
		return
	end
	if not value or value ~= value or math.abs(value * spec.scale) == math.huge then
		setSliderValue(field, state.values[field] or 0)
		setStatus("Enter a finite number")
		return
	end
	beginEditSession()
	if spec.lower then value = math.max(spec.lower, value) end
	if spec.upper then value = math.min(spec.upper, value) end
	if spec.integer then value = math.floor(value) end
	for _, group in pairs(colorGroups) do
		for _, channel in ipairs(group.fields) do
			if field == channel then
				if value < group.threshold then
					for _, key in ipairs(group.fields) do state.values[key] = group.sentinel end
					value = group.sentinel
				else
					value = math.max(0, value)
					-- Editing a channel returns the whole color to custom mode.
					for _, key in ipairs(group.fields) do
						if (state.values[key] or 0) < group.threshold then state.values[key] = 1 end
					end
				end
			end
		end
	end
	state.values[field] = value
	if field == "dirx" or field == "diry" or field == "dirz" then
		local v = state.values
		if v.dirx == 0 and v.diry == 0 and v.dirz == 0 then
			v.dirz = 1
			setStatus("Cone direction must be nonzero; using forward")
		end
	end
	if field == "lifetime" or field == "sustain" then
		local lifetime, sustain = state.values.lifetime or 0, state.values.sustain or 0
		if lifetime > 0 and sustain > 1 and sustain >= lifetime then
			state.values.sustain = math.max(0, lifetime - 1)
			setStatus("Sustain must be shorter than lifetime")
		end
	end
	applyAllValuesToUI()
	applyCurrentLight()
end

