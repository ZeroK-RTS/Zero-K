local function fmtVal(n)
	if type(n) ~= "number" then
		return tostring(n)
	end
	if n == math.floor(n) and math.abs(n) < 1e9 then
		return tostring(math.floor(n))
	end
	return string.format("%.8g", n)
end

local function setSliderValue(field, value)
	state.values[field] = value
	if not state.dmHandle then
		return
	end
	local spec = fieldSpecs[field]
	local min, max = spec.min, spec.max
	if field == "sustain" then
		max = math.max(1, (state.values.lifetime or 0) - 1)
	end
	-- Team-color sentinels belong to the number box, not the color slider.
	if field ~= "r" and field ~= "g" and field ~= "b" and field:sub(1, 6) ~= "color2" then
		min = math.min(min, value)
	end
	max = math.max(max, value)
	local raw = math.floor(math.max(min, math.min(max, value)) * spec.scale + 0.5)
	local wasSyncing = state.syncingInputs
	state.syncingInputs = true
	state.sliderValues = state.sliderValues or {}
	state.sliderValues[field] = raw
	if state.document then
		local slider = state.document:GetElementById("le-slider-" .. field)
		if slider then
			slider:SetAttribute("min", tostring(math.floor(min * spec.scale + 0.5)))
			slider:SetAttribute("max", tostring(math.floor(max * spec.scale + 0.5)))
			slider:SetAttribute("step", "1")
		end
	end
	state.dmHandle["sl_" .. field] = raw
	state.dmHandle["num_" .. field] = fmtVal(value)
	state.syncingInputs = wasSyncing
end

