		lines[#lines + 1] = string.format("%s\tpieceName = %q,", indent, lt.pieceName)
	end
	appendLightMetadata(lines, indent .. "\t", lt)
	local function f(k)
		return fmt(lc[k] or 0)
	end
	lines[#lines + 1] = string.format(
		"%s\tlightConfig = { posx = %s, posy = %s, posz = %s, radius = %s,",
		indent,
		f("posx"),
		f("posy"),
		f("posz"),
		f("radius")
	)
	if (lt.lightType or "point") == "cone" then
		lines[#lines + 1] = string.format(
			"%sdirx = %s, diry = %s, dirz = %s, theta = %s,",
			cfgIndent,
			f("dirx"),
			f("diry"),
			f("dirz"),
			f("theta")
		)
	elseif lt.lightType == "beam" then
		lines[#lines + 1] =
			string.format("%spos2x = %s, pos2y = %s, pos2z = %s,", cfgIndent, f("pos2x"), f("pos2y"), f("pos2z"))
	else
		-- Point-light world-animation params (slots 5-8 under dirx/diry/dirz/theta).
		local hasAnim = (lc.dirx or 0) ~= 0 or (lc.diry or 0) ~= 0 or (lc.dirz or 0) ~= 0 or (lc.theta or 0) ~= 0
		if hasAnim then
			lines[#lines + 1] = string.format(
				"%sdirx = %s, diry = %s, dirz = %s, theta = %s,",
				cfgIndent,
				f("dirx"),
				f("diry"),
				f("dirz"),
				f("theta")
			)
		end
	end
	-- color2 / colortime applies to all light types.
	lines[#lines + 1] = string.format(
		"%scolor2r = %s, color2g = %s, color2b = %s, colortime = %s,",
		cfgIndent,
		f("color2r"),
		f("color2g"),
		f("color2b"),
		f("colortime")
	)
	lines[#lines + 1] = string.format("%sr = %s, g = %s, b = %s, a = %s,", cfgIndent, f("r"), f("g"), f("b"), f("a"))
	lines[#lines + 1] = string.format(
		"%smodelfactor = %s, specular = %s, scattering = %s, lensflare = %s,",
		cfgIndent,
		f("modelfactor"),
		f("specular"),
		f("scattering"),
		f("lensflare")
	)
	lines[#lines + 1] = string.format(
		"%slifetime = %s, sustain = %s, selfshadowing = %s},",
		cfgIndent,
		fmt(math.floor(lc.lifetime or 0)),
		f("sustain"),
		f("selfshadowing")
	)
	lines[#lines + 1] = string.format("%s},", indent)
	return table.concat(lines, "\n")
end

-- Build the entire unit's lights as one `['unitname'] = { ... }` block
-- ready to paste into a LuaRules/Configs/UnitLights file's unitLights table.
local function buildUnitSnippet()
	if not state.currentUnitName or not state.currentUnitDefID then
		return nil, "No unit selected"
	end
	local api = WG["lightsgl4"]
	local udLights = api and api.GetUnitDefLights and api.GetUnitDefLights()
	if not udLights then
		return nil, "Lights API not available"
	end
	local lights = udLights[state.currentUnitDefID]
	if not lights then
		return nil, "No lights for this unit"
	end

	local names = {}
	for n, lt in pairs(lights) do
		if type(lt) == "table" then
			names[#names + 1] = n
		end
	end
	table.sort(names, lightKeyLess)

	local out = {}
	out[#out + 1] = string.format("\t%s = {", luaKey(state.currentUnitName))
	out[#out + 1] = "\t\tstatic = {"
	for _, name in ipairs(names) do
		out[#out + 1] = "\t" .. snippetForLight(name, lights[name]):gsub("\n", "\n\t")
	end
	out[#out + 1] = "\t\t},"
	out[#out + 1] = "\t},"
	return table.concat(out, "\n")
end

local UNDO_LIMIT = 50

local function snapshotValues()
	local s = {
		lightType = state.lightType,
		pieceName = state.pieceName,
		lightName = state.lightName,
		editingExisting = state.editingExisting,
		pointAnim = state.pointAnim,
		selectedLights = {},
		values = {},
	}
	for name in pairs(state.selectedLights) do s.selectedLights[name] = true end
	for k, v in pairs(state.values) do
		s.values[k] = v
	end
	return s
end

-- Captures the full lightParamTable of every currently-selected light so a
-- multi-mode drag can be undone. Only called when multi-mode is active.
local function snapshotMultiSelected(selection)
	local api = WG["lightsgl4"]
	local udLights = api and api.GetUnitDefLights and api.GetUnitDefLights()
	if not udLights or not state.currentUnitDefID then
		return nil
	end
	local unitLights = udLights[state.currentUnitDefID]
	if not unitLights then
		return nil
	end
	local snap = {}
	for name, _ in pairs(selection or state.selectedLights) do
		local lt = unitLights[name]
		if type(lt) == "table" and lt.lightParamTable then
			local copy = {}
			for i = 1, #lt.lightParamTable do
				copy[i] = lt.lightParamTable[i]
			end
			snap[name] = {
				params = copy,
				lightType = lt.lightType,
				pieceIndex = lt.pieceIndex,
			}
		end
	end
	return snap
end

local function pushUndo()
	state.redoStack = {}
	local snap = snapshotValues()
	-- If multi-mode is active, also snapshot every selected light's full
	-- lightParamTable so a multi-drag undo can put them all back.
	if next(state.selectedLights) and countSelectedLights() > 1 then
		snap.multi = snapshotMultiSelected()
	end
	state.undoStack[#state.undoStack + 1] = snap
	if #state.undoStack > UNDO_LIMIT then
		table.remove(state.undoStack, 1)
	end
end

-- Session-scoped push: snapshots only the FIRST mutation since the user last
-- "settled" (released a mouse button or paused for a moment). Multiple edits
-- in the same drag/keypress session collapse into one undo step.
local sessionDirty = false
local lastEditTime = 0

local function beginEditSession()
	if not sessionDirty then
		pushUndo()
		sessionDirty = true
	end
	lastEditTime = os.clock()
end

local function endEditSession()
	sessionDirty = false
end

-- Called from widget:Update() to auto-end a session after 1.0s of inactivity,
-- so isolated keypress-bumps eventually become separate undo steps.
local function checkEditSessionTimeout()
	if sessionDirty and (os.clock() - lastEditTime) > 1.0 then
		sessionDirty = false
	end
end

local function applySnapshot(snap)
	if not snap then
		return
	end
	closePieceDropdown()
	if snap.rename then
		local rename = snap.rename
		if not renameCurrentLight(rename.oldName, true, rename.newName) then
			return false
		end
	end
	state.lightType = snap.lightType
	state.pieceName = snap.pieceName or ""
	state.lightName = snap.lightName or ""
	state.editingExisting = snap.editingExisting
	state.pointAnim = snap.pointAnim or "fade"
	state.selectedLights = {}
	for name in pairs(snap.selectedLights or {}) do state.selectedLights[name] = true end
	for k, _ in pairs(state.values) do
		state.values[k] = nil
	end
	for k, v in pairs(snap.values) do
		state.values[k] = v
	end

	-- Restore the per-light positions captured for a multi-mode drag so
	-- those edits actually rewind in the deferred renderer.
	if snap.multi then
		local api = WG["lightsgl4"]
		local udLights = api and api.GetUnitDefLights and api.GetUnitDefLights()
		local unitLights = udLights and state.currentUnitDefID and udLights[state.currentUnitDefID]
		if unitLights and api and api.AddLight then
			for name, entry in pairs(snap.multi) do
				local lt = unitLights[name]
				if type(lt) == "table" and lt.lightParamTable then
					for i = 1, #entry.params do
						lt.lightParamTable[i] = entry.params[i]
					end
					local vbo = getVBOForType(entry.lightType or lt.lightType or "point")
					if vbo and state.currentUnitID then
						addEditedLight(
							api,
							tostring(state.currentUnitID) .. name,
							state.currentUnitID,
							entry.pieceIndex or lt.pieceIndex or 0,
							vbo,
							lt.lightParamTable
						)
					end
				end
			end
		end
	end
	return true
end

