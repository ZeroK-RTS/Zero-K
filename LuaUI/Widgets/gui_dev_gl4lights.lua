function widget:Initialize()
	state.rmlContext = RmlUi.GetContext("shared")
	if not state.rmlContext then
		spEcho("[LightEditor] no shared RmlUi context")
		return false
	end

	for k, v in pairs(defaultLight) do
		state.values[k] = v
	end

	-- All handlers + bound vars MUST be present at OpenDataModel time.
	-- Adding/replacing functions later is forbidden by Recoil's RmlUi binding.
	local initialModel = {
		-- bound text/values (two-way binding via data-value)
		lightName = state.lightName,
		-- Numeric and slider bindings are populated from fieldSpecs below.

		-- declarative event handlers (data-event-click="onAction('...')")
		onAction = function(_ev, action, arg)
			if action == "toggleGuides" then
				setLightGuides(not state.showLightGuides)
			elseif action == "teamColor" then
				local group = colorGroups[arg]
				if group then
					editField(group.fields[1], group.sentinel)
				end
			elseif action == "toggle" then
				setOpen(not state.open)
				if state.open then
					local sel = spGetSelectedUnits()
					if sel and sel[1] and state.currentUnitID ~= sel[1] then
						setSelectedUnit(sel[1])
					else
						rebuildPieceDropdown()
						rebuildExistingDropdown()
					end
				end
			elseif action == "close" then
				setOpen(false)
			elseif action == "settype" then
				if state.editingExisting and not isMultiMode() and state.lightType ~= arg then
					endEditSession()
					pushUndo()
				end
				setLightType(arg)
			elseif action == "copy" then
				local snippet = generateSnippet()
				if not snippet then
					setStatus("Select a light first")
					return
				end
				if spSetClipboard then
					spSetClipboard(snippet)
				end
				spEcho("[LightEditor] Snippet copied:\n" .. snippet)
				setStatus("Copied to clipboard")
			elseif action == "reset" then
				if not state.editingExisting then return end
				pushUndo()
				resetLightValues()
				setStatus("Reset")
			elseif action == "restartLife" then
				restartLightLife()
			elseif action == "reloadConfig" then
				state.undoStack = {}
				state.redoStack = {}
				endEditSession()
				state.pendingConfigReload = WG["lightsgl4"] or true
				-- Toggle the deferred rendering widget twice via SendCommands
				-- (off, then on). This re-runs its Initialize() which re-reads
				-- DeferredLightsGL4config.lua and rebuilds unitDefLights.
				-- Sent as one command string so they queue up in order.
				Spring.SendCommands(
					"luaui disablewidget Deferred rendering GL4",
					"luaui enablewidget Deferred rendering GL4"
				)
				-- Schedule a follow-up: rebuild our dropdowns and reload the
				-- currently-edited light from the freshly-loaded config.
			elseif action == "titlebarDown" then
				spEcho("[LightEditor] titlebar mousedown received")
				local mxw, myw = Spring.GetMouseState()
				state.titlebarPress = {
					startMx = mxw,
					startMy = myw,
					startLeft = state.panelLeft or 4,
					startTop = state.panelTop or 36,
					moved = false,
				}
			elseif action == "startDragPanel" then
				-- Begin a panel-drag. Capture current mouse pos and panel pos.
				local mxw, myw = Spring.GetMouseState()
				local panel = state.document and state.document:GetElementById("le-panel")
				if not panel then
					return
				end
				state.panelDrag = {
					startMx = mxw,
					startMy = myw,
					-- We store the panel's current top/left in pixel space.
					startLeft = state.panelLeft or 4,
					startTop = state.panelTop or 36,
				}
			elseif action == "startResizePanel" then
				local mxw, myw = Spring.GetMouseState()
				state.panelResize = {
					startMx = mxw,
					startMy = myw,
					startW = state.panelWidth or 460,
					startH = state.panelHeight or 800,
				}
			elseif action == "addLight" then
				addNewLight()
			elseif action == "toggleExistingDropdown" then
				rebuildExistingDropdown()
				local listEl = state.document and state.document:GetElementById("le-existing-list")
				if listEl then
					local hidden = (listEl:GetAttribute("style") or ""):find("none")
					listEl:SetAttribute(
						"style",
						DROPDOWN_LIST_STYLE .. (hidden and "display: block;" or "display: none;")
					)
				end
			elseif action == "togglePieceDropdown" then
				local listEl = state.document and state.document:GetElementById("le-piece-list")
				if listEl then
					local hidden = (listEl:GetAttribute("style") or ""):find("none")
					state.highlightPiece = nil
					state.pieceDropdownOpen = hidden ~= nil
					listEl:SetAttribute(
						"style",
						DROPDOWN_LIST_STYLE .. (hidden and "display: block;" or "display: none;")
					)
				end
			elseif action == "hoverPiece" then
				state.highlightPiece = state.pieceDropdownOpen
					and state.pieceMap and state.pieceMap[arg] and arg or nil
			elseif action == "hoverPieceSelector" then
				state.pieceSelectorHovered = arg == "1"
			elseif action == "selectExisting" then
