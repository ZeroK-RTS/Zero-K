			local teamID = Spring.GetUnitTeam(state.currentUnitID)
			if teamID then
				r, g, b = Spring.GetTeamColor(teamID)
			end
		end
	end
	r = math.max(0, math.min(255, math.floor((r or 0) * 255)))
	g = math.max(0, math.min(255, math.floor((g or 0) * 255)))
	b = math.max(0, math.min(255, math.floor((b or 0) * 255)))
	sw:SetAttribute("style", string.format("background-color: #%02X%02X%02X;", r, g, b))
end

local function applyCurrentLight()
	updateSwatch()
	if not state.currentUnitID or not state.editingExisting or isMultiMode() then
		return
	end
	local api = WG["lightsgl4"]
	local definitions = api and api.GetUnitDefLights and api.GetUnitDefLights()
	local lights = definitions and definitions[state.currentUnitDefID]
	local light = lights and lights[state.editingExisting]
	local vbo = getVBOForType(state.lightType)
	if type(light) ~= "table" or not api.AddLight or not vbo then
		return
	end
	local instanceID = tostring(state.currentUnitID) .. state.editingExisting
	-- Same-shape updates preserve the existing spawn frame.
	for _, lightType in ipairs({ "point", "cone", "beam" }) do
		local oldVBO = getVBOForType(lightType)
		if lightType ~= state.lightType and oldVBO and oldVBO.instanceIDtoIndex[instanceID] then
			api.RemoveLight(lightType, instanceID, state.currentUnitID)
		end
	end
	local pieceIndex = state.pieceMap and state.pieceMap[state.pieceName] or 0
	local params = buildLightParamTable()
	addEditedLight(api, instanceID, state.currentUnitID, pieceIndex, vbo, params)
	light.lightParamTable = params
	light.lightConfig = nil
	light.initComplete = true
	light.pieceIndex = pieceIndex
	light.pieceName = state.pieceName ~= "" and state.pieceName or nil
	light.lightType = state.lightType
	recordCurrentAsOverride()
	updateLightSelector()
end

