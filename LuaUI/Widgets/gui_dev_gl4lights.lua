local function restartLightLife()
	if not state.currentUnitID or not state.editingExisting or isMultiMode() then
		setStatus("Select a light first")
		return
	end
	local api = WG["lightsgl4"]
	local definitions = api and api.GetUnitDefLights and api.GetUnitDefLights()
	local light = definitions and definitions[state.currentUnitDefID] and definitions[state.currentUnitDefID][state.editingExisting]
	local vbo = getVBOForType(state.lightType)
	if type(light) ~= "table" or not vbo or not api.AddLight then
		setStatus("Lights API unavailable")
		return
	end
	endEditSession()
	local restartFrame = Spring.GetGameFrame()
	local instanceID = tostring(state.currentUnitID) .. state.editingExisting
	local index = vbo.instanceIDtoIndex[instanceID]
	if not index then
		-- Recreate expired lights before resetting their timestamp. AddLight
		-- otherwise uses the renderer's cached frame for new instances, which
		-- can lag behind the current engine frame between call-ins or on reload.
		applyCurrentLight()
		index = vbo.instanceIDtoIndex[instanceID]
	end
	if not index then
		setStatus("Could not restart light")
		return
	end
	-- Both live and recreated lights start at exactly the same engine time.
	vbo.instanceData[(index - 1) * vbo.instanceStep + 17] = restartFrame
	applyCurrentLight()
	setStatus("Light lifetime restarted")
end

local function clearChildren(element)
	if not element then
		return
	end
	-- Try inner_rml first (PR #7219 pattern); fall back to RemoveChild if needed.
	pcall(function()
		element.inner_rml = ""
	end)
	-- Some RmlUi bindings keep <option> children even after inner_rml clear; force-remove.
	local guard = 0
	while element.first_child and guard < 200 do
		pcall(function()
			element:RemoveChild(element.first_child)
		end)
		guard = guard + 1
	end
end

-- Escape arbitrary string to safe RML attribute value (just enough for option
-- values: quotes and angle brackets). Light/piece names in BAR are simple
-- identifiers, but be defensive.
local function rmlEscape(s)
	s = tostring(s)
	s = s:gsub("&", "&amp;"):gsub("<", "&lt;"):gsub(">", "&gt;"):gsub('"', "&quot;")
	return s
end

