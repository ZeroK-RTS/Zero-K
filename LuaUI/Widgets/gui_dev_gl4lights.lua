local function addEditedLight(api, instanceID, unitID, pieceIndex, vbo, params, noUpload)
	-- AddLight queues each finite expiry without cancelling previous ones.
	-- Remove only this edited instance's pending entries before rescheduling,
	-- including entries for an earlier shape or a reused name after undo.
	local queue = api.GetLightRemoveQueue and api.GetLightRemoveQueue()
	if queue then
		for frame, removals in pairs(queue) do
			if removals[instanceID] then
				removals[instanceID] = nil
				if not next(removals) then queue[frame] = nil end
			end
		end
	end
	return api.AddLight(instanceID, unitID, pieceIndex, vbo, params, noUpload)
end

