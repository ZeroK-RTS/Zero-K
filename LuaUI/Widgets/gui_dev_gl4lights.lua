			state.focusedField = nil
			Spring.SDLStopTextInput()
		end,
	}

	for _, field in ipairs(sliderFields) do
		initialModel["sl_" .. field] = math.floor(state.values[field] * sliderScale[field] + 0.5)
		initialModel["num_" .. field] = fmtVal(state.values[field])
	end
