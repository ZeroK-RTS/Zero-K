selectDefaultLight = function()
	local api = WG["lightsgl4"]
	local definitions = api and api.GetUnitDefLights and api.GetUnitDefLights()
	local lights = definitions and definitions[state.currentUnitDefID]
	local name = state.editingExisting
	if not lights or type(lights[name]) ~= "table" then
		local names = {}
		for key, light in pairs(lights or {}) do
			if type(light) == "table" then names[#names + 1] = key end
		end
		table.sort(names, lightKeyLess)
		name = names[1]
	end
	state.selectedLights = name and {[name] = true} or {}
	if name then
		loadExistingLight(name)
	else
		state.editingExisting = nil
		state.lightName = ""
		resetLightValues()
	end
	refreshMultiModeUI()
	updateLightSelector()
end

local function addNewLight()
	local api = WG["lightsgl4"]
	local definitions = api and api.GetUnitDefLights and api.GetUnitDefLights()
	if not state.currentUnitID or not state.currentUnitDefID then
		setStatus("Select a unit first")
		return
	end
	if not definitions or not api.AddLight or not getVBOForType("point") then
		setStatus("Lights API unavailable")
		return
	end
	local lights = definitions[state.currentUnitDefID]
	local sourceName = state.editingExisting
	if not lights or type(lights[sourceName]) ~= "table" then
		-- With multiple lights selected, copy the first selected light. If
		-- none is selected, use the first existing light for this unit.
		local names = {}
		for name in pairs(state.selectedLights) do
			if lights and type(lights[name]) == "table" then names[#names + 1] = name end
		end
		if #names == 0 then
			for name, light in pairs(lights or {}) do
				if type(light) == "table" then names[#names + 1] = name end
			end
		end
		table.sort(names, lightKeyLess)
		sourceName = names[1]
		if sourceName then
			state.selectedLights = {[sourceName] = true}
			loadExistingLight(sourceName)
		end
	end
	local source = lights and lights[sourceName]
	local light
	if type(source) == "table" then
		if not source.lightParamTable then
			state.selectedLights = {[sourceName] = true}
			loadExistingLight(sourceName)
		end
		-- Copy metadata and parameters independently; only the new instance's
		-- identity and spawn time change.
		light = Spring.Utilities.CopyTable(source, true)
		light.lightParamTable[17] = 0
		for i = 26, lightParamSize do light.lightParamTable[i] = 0 end
	else
		state.editingExisting = nil
		state.selectedLights = {}
		resetLightValues()
		light = {
			lightType = "point",
			pieceIndex = 0,
			lightParamTable = buildLightParamTable(),
			initComplete = true,
		}
	end
	local newName = "New Light"
	local suffix = 1
	while lights and lights[newName] do
		suffix = suffix + 1
		newName = "New Light " .. suffix
	end
	definitions[state.currentUnitDefID] = definitions[state.currentUnitDefID] or {}
	state.redoStack = {}
	definitions[state.currentUnitDefID][newName] = light
	state.selectedLights = {[newName] = true}
	loadExistingLight(newName)
	refreshMultiModeUI()
	rebuildExistingDropdown()
	setStatus("Added '" .. newName .. "'")
end

renameCurrentLight = function(newName, undo, oldName)
	oldName = oldName or state.editingExisting
	if not undo then
		if type(newName) ~= "string" then return false end
		newName = newName:match("^%s*(.-)%s*$")
		if newName == "" or newName:find("%c") or newName == "initComplete" or newName == "__new__" then
			if state.dmHandle then state.dmHandle.lightName = state.lightName end
			setStatus("Enter a nonempty, unique light name")
			return false
		end
	end
	if oldName and tostring(oldName) == newName then
		if state.dmHandle then state.dmHandle.lightName = state.lightName end
		return true
	end
	if not oldName then
		if state.dmHandle then state.dmHandle.lightName = state.lightName end
		setStatus("Select a light or click + Add")
		return false
	end
	local api = WG["lightsgl4"]
	local definitions = api and api.GetUnitDefLights and api.GetUnitDefLights()
	local lights = definitions and definitions[state.currentUnitDefID]
	local target = lights and resolveLightKey(lights, newName)
	local light = lights and lights[oldName]
	local vbo = light and getVBOForType(light.lightType or "point")
	if type(light) ~= "table" or not vbo or not api.RemoveLight or not api.AddLight then
		setStatus("Lights API unavailable")
		if state.dmHandle then state.dmHandle.lightName = state.lightName end
		return false
	end
	if lights[target] and target ~= oldName then
		setStatus("A light with that name already exists")
		if state.dmHandle then state.dmHandle.lightName = state.lightName end
		return false
	end
	-- Recreate only instances that already exist; the definition is shared
	-- by every unit of this type. Keep renderer bookkeeping behind its API.
	local instances = {}
	for _, unitID in ipairs(Spring.GetAllUnits()) do
		if spGetUnitDefID(unitID) == state.currentUnitDefID then
			local oldID, newID = tostring(unitID) .. oldName, tostring(unitID) .. newName
			local index = vbo.instanceIDtoIndex[oldID]
			if index then
				if vbo.instanceIDtoIndex[newID] then
					setStatus("A rendered light with that name already exists")
					if state.dmHandle then state.dmHandle.lightName = state.lightName end
					return false
				end
				local params = {}
				for i = 1, lightParamSize do
					params[i] = vbo.instanceData[(index - 1) * vbo.instanceStep + i]
				end
				instances[#instances + 1] = {unitID = unitID, oldID = oldID, newID = newID, params = params}
			end
		end
	end
	if not undo then
		endEditSession()
		pushUndo()
		state.undoStack[#state.undoStack].rename = {oldName = oldName, newName = newName}
	end
	lights[newName], lights[oldName] = light, nil
	for _, entry in ipairs(instances) do
		api.RemoveLight(light.lightType or "point", entry.oldID, entry.unitID)
		local params = entry.params
		local spawnFrame, lifetime = params[17], params[18]
		-- AddLight initializes new instances at the current frame. Stage the
		-- replacement without expiry, then restore its frame before the final
		-- update so animations and expiry retain their original timing.
		params[18] = 0
		addEditedLight(api, entry.newID, entry.unitID, light.pieceIndex or 0, vbo, params)
		local index = vbo.instanceIDtoIndex[entry.newID]
		vbo.instanceData[(index - 1) * vbo.instanceStep + 17] = spawnFrame
		params[17], params[18] = spawnFrame, lifetime
		addEditedLight(api, entry.newID, entry.unitID, light.pieceIndex or 0, vbo, params)
	end
	state.editingExisting = newName
	state.lightName = tostring(newName)
	if state.selectedLights[oldName] then
		state.selectedLights[oldName], state.selectedLights[newName] = nil, true
	end
	if state.hoveredLightMarker == oldName then state.hoveredLightMarker = newName end
	if state.currentUnitName then
		state.overrides[state.currentUnitName] = state.overrides[state.currentUnitName] or {}
		state.overrides[state.currentUnitName][oldName] = "__deleted__"
		recordCurrentAsOverride()
	end
	if state.dmHandle then state.dmHandle.lightName = state.lightName end
	rebuildExistingDropdown()
	setStatus("Renamed light to '" .. tostring(newName) .. "'")
	return true
end

local function restoreHistory(redo)
	local source = redo and state.redoStack or state.undoStack
	local destination = redo and state.undoStack or state.redoStack
	local label = redo and "Redo" or "Undo"
	local snap = source[#source]
	if not snap then
		setStatus(redo and "Nothing to redo" or "Nothing to undo")
		return
	end
	state.dragging = nil
	state.gizmo = nil
	endEditSession()
	-- Capture the affected light even if another light is now selected.
	local name = snap.rename and snap.rename.newName or snap.editingExisting
	if not snap.multi and name and not loadExistingLight(name) then
		setStatus("Light no longer exists")
		return
	end
	local inverse = snapshotValues()
	if snap.multi then
		inverse.multi = snapshotMultiSelected(snap.multi)
		inverse.selectedLights = Spring.Utilities.CopyTable(snap.selectedLights, true)
		inverse.editingExisting = snap.editingExisting
	end
	if snap.rename then
		inverse.rename = {oldName = snap.rename.newName, newName = snap.rename.oldName}
	end
	if not applySnapshot(snap) then return end
	table.remove(source)
	destination[#destination + 1] = inverse
	if #destination > UNDO_LIMIT then table.remove(destination, 1) end
	refreshMultiModeUI()
	applyAllValuesToUI()
	local pieceDisplay = state.document and state.document:GetElementById("le-piece-display")
	if pieceDisplay then
		pieceDisplay.inner_rml = state.pieceName ~= "" and state.pieceName or "(unit origin)"
	end
	setLightType(state.lightType)
	setStatus(label .. " (" .. #source .. " remaining)")
end

