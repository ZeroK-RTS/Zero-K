	if not dm then
		spEcho("[LightEditor] failed to open data model")
		return false
	end
	state.dmHandle = dm

	local document = state.rmlContext:LoadDocument(RML_PATH, self)
	if not document then
		spEcho("[LightEditor] failed to load document")
		state.rmlContext:RemoveDataModel(MODEL_NAME)
		return false
	end
	state.document = document
	closePieceDropdown()
	state.tooltipRenderedKey = nil
	document:Show()
	initPieceHighlightShader()

	-- Width forced; height comes from the RCSS class (95vh + max-height).
	local panel = document:GetElementById("le-panel")
	if panel and panel.SetProperty then
		panel:SetProperty("left", "0dp")
		panel:SetProperty("top", "0dp")
		panel:SetProperty("width", "400dp")
	end

	attachAllListeners()
	applyAllValuesToUI()
	setLightType("point")
	updateSwatch()
	setOpen(state.open)
	setLightGuides(state.showLightGuides)
	updateLightSelector()

