local function initPieceHighlightShader()
	if pieceHighlightShader then return end
	if gl.CreateShader and gl.ActiveShader and gl.UnitPiece and gl.UniformMatrix then
		pieceHighlightShader = gl.CreateShader({
			vertex = [[
				#version 330 compatibility
				layout(location = 0) in vec3 position;
				uniform mat4 viewProjection;
				uniform mat4 modelWorld;
				uniform mat4 pieceModel;
				void main() {
					gl_Position = viewProjection * modelWorld * pieceModel * vec4(position, 1.0);
				}
			]],
			fragment = [[
				#version 330 compatibility
				uniform vec4 highlightColor;
				out vec4 fragColor;
				void main() {
					fragColor = highlightColor;
				}
			]],
		})
		if pieceHighlightShader and pieceHighlightShader ~= 0 then
			pieceHighlightColorLoc = gl.GetUniformLocation(pieceHighlightShader, "highlightColor")
			pieceHighlightViewProjLoc = gl.GetUniformLocation(pieceHighlightShader, "viewProjection")
			pieceHighlightModelLoc = gl.GetUniformLocation(pieceHighlightShader, "modelWorld")
			pieceHighlightPieceLoc = gl.GetUniformLocation(pieceHighlightShader, "pieceModel")
			return
		end
	end
	pieceHighlightShader = nil
	if not pieceHighlightWarningShown then
		pieceHighlightWarningShown = true
		spEcho("[LightEditor] Piece overlay unavailable; empty pieces still use origin markers. " .. tostring(gl.GetShaderLog and gl.GetShaderLog() or ""))
	end
end

